import { describe, expect, it } from 'vitest';
import { distinctProblems, withoutEndPunctuation } from '@/pages/analysis/report-text';

describe('тексты отчёта от модели', () => {
  it('«Что отнимает время»: одна боль разными словами — один раз, остаётся полная формулировка', () => {
    expect(
      distinctProblems([
        'Менеджеры вручную отвечают на одни и те же вопросы о размерах и доставке',
        'менеджеры вручную отвечают на одни и те же вопросы о размерах и доставке.',
        'Менеджеры вручную отвечают на одни и те же вопросы',
        'Заказы ведутся в таблицах вручную',
        '  ',
        'Ёлки: остатки считают вручную',
        'Елки — остатки считают вручную!',
      ]),
    ).toEqual([
      'Менеджеры вручную отвечают на одни и те же вопросы о размерах и доставке',
      'Заказы ведутся в таблицах вручную',
      'Ёлки: остатки считают вручную',
    ]);
  });

  it('более полная формулировка заменяет короткую, пришедшую раньше', () => {
    expect(distinctProblems(['Долгие ответы', 'Долгие ответы клиентам в WhatsApp'])).toEqual([
      'Долгие ответы клиентам в WhatsApp',
    ]);
  });

  it('причина без своей точки в конце: фраза отчёта ставит точку сама', () => {
    expect(withoutEndPunctuation('Подключение к WhatsApp Business API.')).toBe(
      'Подключение к WhatsApp Business API',
    );
    expect(withoutEndPunctuation('Интеграция с 1С!? ')).toBe('Интеграция с 1С');
    expect(withoutEndPunctuation('Отправка писем')).toBe('Отправка писем');
  });
});
